// Erzeugt aus prisma/schema.prisma genau EINE Baseline-Migration (00000000000000_baseline) neu und ersetzt dabei alle bisherigen
// Migrationsordner. Gilt nur, solange die Baseline nicht veröffentlicht ist (erste Zeile "-- schrauberos:baseline unreleased"):
//   npm run db:baseline      nach jeder Schema-Änderung dieses Releases (danach: npm run db:fresh)
// Mit der Veröffentlichung wird die Baseline auf "frozen" gesetzt (Release-Block); ab dann verweigert dieses Skript die Arbeit und
// Schema-Änderungen laufen über `npm run db:migrate -- <name>` (nur additiv, vom Wächter src/lib/migration-guard.ts geprüft).
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const migrations = resolve(root, "prisma/migrations");
const BASELINE = "00000000000000_baseline";
const MARKER = "-- schrauberos:baseline";
const file = resolve(migrations, BASELINE, "migration.sql");

if (existsSync(file)) {
  const first = readFileSync(file, "utf8").split(/\r?\n/, 1)[0];
  if (first.startsWith(MARKER) && first.includes("frozen")) {
    console.error("Die Baseline ist veröffentlicht (frozen) und wird nie neu erzeugt. Schema-Änderung: npm run db:migrate -- <name>");
    process.exit(1);
  }
}

const sql = execFileSync(process.execPath, [resolve(root, "node_modules/prisma/build/index.js"), "migrate", "diff", "--from-empty", "--to-schema", "prisma/schema.prisma", "--script"], {
  cwd: root,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
  env: { ...process.env, DATABASE_URL: process.env.DATABASE_URL ?? "file:./dev.db" },
}).replace(/\r\n/g, "\n");
if (!/CREATE TABLE/.test(sql)) {
  console.error("Prisma lieferte kein SQL – Baseline nicht geändert.");
  process.exit(1);
}

for (const entry of readdirSync(migrations, { withFileTypes: true })) {
  if (entry.isDirectory()) rmSync(resolve(migrations, entry.name), { recursive: true, force: true });
}
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, `${MARKER} unreleased (erzeugt mit npm run db:baseline aus prisma/schema.prisma – nicht von Hand ändern)\n${sql.trimEnd()}\n`);
if (!existsSync(resolve(migrations, "migration_lock.toml"))) writeFileSync(resolve(migrations, "migration_lock.toml"), "# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = \"sqlite\"\n");
console.log("Baseline neu erzeugt: prisma/migrations/00000000000000_baseline/migration.sql");
console.log("Lokale Datenbank neu aufbauen: npm run db:fresh");
