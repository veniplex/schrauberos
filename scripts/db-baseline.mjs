// Entwicklungsphase: statt einer wachsenden Migrationshistorie gibt es je Datenbank genau EINE Baseline-Migration,
// die aus dem aktuellen Schema erzeugt wird. Nach jeder Schema-Änderung:
//   npm run db:baseline   → Schema ableiten, Baselines neu erzeugen
//   npm run db:fresh      → lokale SQLite-Entwicklungsdatenbank löschen, neu anlegen und seeden
// Sobald echte Daten existieren, wird auf normale Migrationen (`prisma migrate dev`) umgestellt.
import { execFileSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const run = (args, env = {}) =>
  execFileSync(process.execPath, [resolve(root, "node_modules/prisma/build/index.js"), ...args], {
    cwd: root,
    encoding: "utf8",
    env: { ...process.env, ...env },
  });

execFileSync(process.execPath, [resolve(root, "scripts/sync-pg-schema.mjs")], { cwd: root, stdio: "inherit" });

const targets = [
  { name: "SQLite", schema: "prisma/schema.prisma", dir: "prisma/migrations", provider: "sqlite", url: "file:./dev.db" },
  { name: "PostgreSQL", schema: "prisma/postgres/schema.prisma", dir: "prisma/postgres/migrations", provider: "postgresql", url: "postgresql://x:x@localhost:5432/x" },
];

for (const t of targets) {
  const sql = run(["migrate", "diff", "--from-empty", "--to-schema", t.schema, "--script"], { DATABASE_URL: t.url });
  rmSync(resolve(root, t.dir), { recursive: true, force: true });
  mkdirSync(resolve(root, t.dir, "00000000000000_baseline"), { recursive: true });
  writeFileSync(resolve(root, t.dir, "00000000000000_baseline/migration.sql"), sql);
  writeFileSync(resolve(root, t.dir, "migration_lock.toml"), `# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "${t.provider}"\n`);
  console.log(`${t.name}: Baseline neu erzeugt (${sql.split("\n").length} Zeilen).`);
}
run(["generate"], { DATABASE_URL: "file:./dev.db" });
